pub fn random_success_prefix() -> &'static str {
    let mut rng = rand::thread_rng();
    SUCCESS_PREFIXES[rng.gen_range(0..SUCCESS_PREFIXES.len())]
}

pub fn random_missed_lore(exp_gain: u128) -> String {
    let mut rng = rand::thread_rng();
    let base = MISSED_LORE_TEMPLATES[rng.gen_range(0..MISSED_LORE_TEMPLATES.len())];
    format!("错失奇遇：{}（仙缘 +{}）", base, exp_gain)
}
