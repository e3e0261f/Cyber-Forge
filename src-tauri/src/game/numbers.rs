pub fn format_compact_number(n: u128) -> String {
    match n {
        0..=999_999 => {
            let s = n.to_string();
            let mut result = String::new();
            let len = s.len();
            for (i, ch) in s.chars().enumerate() {
                if i > 0 && (len - i) % 3 == 0 {
                    result.push(',');
                }
                result.push(ch);
            }
            format!("{:>8}", result)
        }
        // 10^6 (M)
        1_000_000..=999_999_999 => {
            format!("{:>7.2}M", n as f64 / 1_000_000.0)
        }
        // 10^9 (G)
        1_000_000_000..=999_999_999_999 => {
            format!("{:>7.2}G", n as f64 / 1_000_000_000.0)
        }
        // 10^12 (T)
        1_000_000_000_000..=999_999_999_999_999 => {
            format!("{:>7.2}T", n as f64 / 1_000_000_000_000.0)
        }
        // 10^15 (P)
        1_000_000_000_000_000..=999_999_999_999_999_999 => {
            format!("{:>7.2}P", n as f64 / 1_000_000_000_000_000.0)
        }
        // 10^18 (E)
        1_000_000_000_000_000_000..=999_999_999_999_999_999_999 => {
            format!("{:>7.2}E", n as f64 / 1_000_000_000_000_000_000.0)
        }
        // 10^21 (Z)
        1_000_000_000_000_000_000_000..=999_999_999_999_999_999_999_999 => {
            format!("{:>7.2}Z", n as f64 / 1_000_000_000_000_000_000_000.0)
        }
        // 10^24 及以上 (Y)
        _ => {
            let val = n as f64 / 1_000_000_000_000_000_000_000_000.0;
            format!("{:>6.2}Y", val)
        }
    }
}
