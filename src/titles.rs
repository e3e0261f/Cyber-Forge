pub struct TitleSystem;

impl TitleSystem {
    pub fn get_title_by_level(level: u32) -> &'static str {
        match level {
            1..=15   => "凡铁打刀客",    // 炼体 身体强度，
            16..=30  => "赛博引气匠",    // 炼气 气感
            31..=45  => "纳米识海者",    // 练神 精神力多少
            46..=60  => "高能内核体",    // 金丹 金丹个数、大小、凝缩强度
            61..=75  => "赛博数字婴",    // 元婴 元婴大小、个数、元婴强度 多核并发
            76..=90  => "量子态化神",    // 化神 气机强度 矩阵
            91..=105 => "矩阵合体尊",    // 合体 法则碎片数量 反重力
            106..=120=> "虚空淬火尊",    // 大乘 雷劫强度 因果律
            121..=135=> "反重力真仙",    // 仙人 法则掌控力
            136..=150=> "因果律圣者",    // 圣人 因果掌控力
            151..=165=> "天道炉火仙",    // 天道境 终极热力学
            166..=180=> "熵增造物神",    // 至尊境 熵增开关
            _        => "熵增造物神",
        }
    }
}


